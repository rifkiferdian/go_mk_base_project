CREATE TABLE employee_placement_change_requests (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    employee_id BIGINT UNSIGNED NOT NULL,
    current_assignment_id BIGINT UNSIGNED NOT NULL,
    requested_position_id BIGINT UNSIGNED NOT NULL,
    requested_store_id BIGINT UNSIGNED NOT NULL,
    effective_date DATE NOT NULL,
    reason TEXT NOT NULL,
    status ENUM('pending','approved','rejected','cancelled') NOT NULL DEFAULT 'pending',
    requested_by_user_id BIGINT UNSIGNED NOT NULL,
    decided_by_user_id BIGINT UNSIGNED NULL,
    decision_notes TEXT NULL,
    decided_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    KEY placement_request_status_date(status,effective_date),
    KEY placement_request_employee(employee_id,created_at),
    CONSTRAINT placement_request_employee_fk FOREIGN KEY(employee_id) REFERENCES employees(id),
    CONSTRAINT placement_request_assignment_fk FOREIGN KEY(current_assignment_id) REFERENCES employee_assignments(id),
    CONSTRAINT placement_request_position_fk FOREIGN KEY(requested_position_id) REFERENCES positions(id),
    CONSTRAINT placement_request_store_fk FOREIGN KEY(requested_store_id) REFERENCES stores(id),
    CONSTRAINT placement_request_requester_fk FOREIGN KEY(requested_by_user_id) REFERENCES users(id),
    CONSTRAINT placement_request_decider_fk FOREIGN KEY(decided_by_user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
