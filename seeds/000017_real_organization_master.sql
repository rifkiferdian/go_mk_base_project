INSERT INTO positions(job_level_id,department_id,code,name)
SELECT l.id,d.id,p.code,p.name
FROM real_positions p
JOIN job_levels l ON l.code=p.level_code
JOIN departments d ON d.code=p.department_code
ON DUPLICATE KEY UPDATE job_level_id=VALUES(job_level_id),department_id=VALUES(department_id),name=VALUES(name);

